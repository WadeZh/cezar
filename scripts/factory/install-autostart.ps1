# factory install-autostart (spec §5): schtasks ONLOGON 计划任务 + 卸载入口。
# - LiteralPath everywhere (paths with spaces must work)
# - background launch: powershell -WindowStyle Hidden → no extra console window
# - ONLOGON only: 登录后自启动 ≠ 未登录也能运行（spec §5 明确要求分别验证）

param(
  [switch]$Uninstall,
  [string]$RepoRoot = (Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $PSCommandPath))),
  [string]$TaskName = 'CezarFactory',
  [string]$Port = '4321'
)

$ErrorActionPreference = 'Stop'
$scriptDir = Split-Path -Parent $PSCommandPath
$launcher = Join-Path $scriptDir 'run-factory-hidden.ps1'

function Write-Launcher {
  # The hidden launcher: starts the built server detached; a second boot is a no-op
  # (scripts/factory/start.mjs answers "already running" and exits 0 — singleton by design).
  $content = @"
# Auto-generated by install-autostart.ps1 — do not edit; reinstall instead.
`$env:CEZ_PORT = '$Port'
& node "$RepoRoot\scripts\factory\start.mjs"
"@
  Set-Content -LiteralPath $launcher -Value $content -Encoding UTF8
}

if ($Uninstall) {
  $existing = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
  if ($existing) {
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
    Write-Output "uninstalled scheduled task '$TaskName'"
  } else {
    Write-Output "scheduled task '$TaskName' not present — nothing to uninstall"
  }
  if (Test-Path -LiteralPath $launcher) {
    Remove-Item -LiteralPath $launcher -Force
    Write-Output "removed launcher $launcher"
  }
  exit 0
}

if (-not (Test-Path -LiteralPath (Join-Path $RepoRoot 'packages\cezar\dist\index.js'))) {
  Write-Error "built server missing under $RepoRoot — run 'npm run build' before installing autostart"
}

Write-Launcher

$action = New-ScheduledTaskAction -Execute 'powershell.exe' `
  -Argument "-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$launcher`""
$trigger = New-ScheduledTaskTrigger -AtLogOn
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
  -ExecutionTimeLimit (New-TimeSpan -Hours 0)
Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings -Force | Out-Null

Write-Output "installed scheduled task '$TaskName' (at log on, hidden):"
Write-Output "  launcher : $launcher"
Write-Output "  repo     : $RepoRoot"
Write-Output "  port     : $Port"
Write-Output "uninstall : powershell -File $PSCommandPath -Uninstall"
Write-Output '注意：这是"用户登录后自启动"；未登录时的行为（电源/会话设置）需按 docs/factory/README.md 单独验证。'
